/** Four categories with four words each; [words] is the 16 words in shuffled order. */
class Puzzle(val groups: List<Category>, val words: List<String>)

fun newPuzzle(rng: Random): Puzzle {
    val groups = CATEGORIES.shuffled(rng).take(GROUPS).map { Category(it.name, it.words.shuffled(rng).take(PER_GROUP)) }
    return Puzzle(groups, groups.flatMap { it.words }.shuffled(rng))
}

/** Index of the group that is exactly [picked], or null. */
fun groupOf(p: Puzzle, picked: Set<String>) = p.groups.indexOfFirst { it.words.toSet() == picked }.takeIf { it >= 0 }

/** True when three of the four picked words share a group: worth telling the player. */
fun oneAway(p: Puzzle, picked: Set<String>) = p.groups.any { g -> g.words.count { it in picked } == PER_GROUP - 1 }

/** Solved group indexes in the order found, mistakes, seconds. */
fun encodeGame(solved: List<Int>, mistakes: Int, seconds: Int) = solved.joinToString("") + ";" + mistakes + ";" + seconds

fun decodeGame(text: String): Triple<List<Int>, Int, Int> {
    val (a, m, s) = text.split(";")
    val solved = a.map { it.digitToInt() }
    require(solved.all { it < GROUPS } && solved.toSet().size == solved.size && solved.size < GROUPS && m.toInt() in 0 until MAX_MISTAKES)
    return Triple(solved, m.toInt(), s.toInt())
}
