private val ORDER = WORDS.shuffled(Random(42))

/** Levels walk through a fixed shuffle, so no word repeats until all are used; a daily seed picks the same way. */
fun wordFor(seed: Long) = ORDER[Math.floorMod(seed, ORDER.size.toLong()).toInt()]

/**
 * Marks for each letter of [guess]: right place, in the word elsewhere, or not in it.
 * A letter is marked "elsewhere" at most as many times as the answer still has it after right-place letters.
 */
fun score(guess: String, answer: String): IntArray {
    val out = IntArray(LEN)
    val left = IntArray(26)
    for (i in 0 until LEN) if (guess[i] == answer[i]) out[i] = CORRECT else left[answer[i] - 'A']++
    for (i in 0 until LEN) if (out[i] != CORRECT && left[guess[i] - 'A'] > 0) { out[i] = PRESENT; left[guess[i] - 'A']-- }
    return out
}

/** Best mark seen for each letter, for colouring the keyboard. */
fun keyMarks(guesses: List<String>, answer: String): Map<Char, Int> {
    val best = HashMap<Char, Int>()
    for (g in guesses) score(g, answer).forEachIndexed { i, m -> best[g[i]] = maxOf(best[g[i]] ?: ABSENT, m) }
    return best
}

/**
 * shortcut: any five letters count as a guess (the repo has no full dictionary to check against);
 * add a word-list asset and reject unknown words if players ask for it.
 */
fun isGuess(text: String) = text.length == LEN && text.all { it in 'A'..'Z' }

/** Hint: the first position not yet guessed right and not already shown. Null when nothing is left to show. */
fun nextHint(guesses: List<String>, shown: Set<Int>, answer: String) =
    (0 until LEN).firstOrNull { i -> i !in shown && guesses.none { it[i] == answer[i] } }

fun encodeGame(guesses: List<String>, shown: Set<Int>) = guesses.joinToString(",") + ";" + shown.sorted().joinToString("")

fun decodeGame(text: String): Pair<List<String>, Set<Int>> {
    val (g, h) = text.split(";")
    val guesses = if (g.isEmpty()) emptyList() else g.split(",")
    require(guesses.size < TRIES && guesses.all { isGuess(it) })
    return guesses to h.map { it.digitToInt().also { p -> require(p < LEN) } }.toSet()
}
