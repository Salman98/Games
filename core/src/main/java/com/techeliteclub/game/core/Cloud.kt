import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import com.google.android.gms.tasks.Task
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.Firebase
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.auth
import com.google.firebase.firestore.FieldValue
import com.google.firebase.firestore.firestore
import kotlinx.coroutines.suspendCancellableCoroutine
import kotlin.coroutines.resume
import kotlin.coroutines.resumeWithException

/**
 * Google Sign-In (Firebase Auth) and cloud save (Firestore). One account works across every game;
 * each game's progress lives at users/{uid}/games/{packageName}.
 */
object Cloud {
    /** False for a game whose google-services.json has not been added yet. */
    fun available(context: Context) = FirebaseApp.getApps(context).isNotEmpty()

    val user: FirebaseUser? get() = Firebase.auth.currentUser

    /** Shows the Google account picker, signs in to Firebase, then restores this game's save (or uploads it if none). */
    suspend fun signIn(activity: Activity, store: GameStore) {
        // Generated by the google-services plugin into the game module, so core can't use R for it (kept by res/raw/keep.xml).
        val id = activity.resources.getIdentifier("default_web_client_id", "string", activity.packageName)
        check(id != 0) { "Enable Google sign-in in Firebase, then re-download google-services.json" }
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(activity.getString(id)).build())
            .build()
        val credential = CredentialManager.create(activity).getCredential(activity, request).credential
        val token = GoogleIdTokenCredential.createFrom(credential.data).idToken
        Firebase.auth.signInWithCredential(GoogleAuthProvider.getCredential(token, null)).await()
        val saved = doc(activity).get().await()
        if (saved.exists()) store.putAll(SaveCodec.decode(saved.data.orEmpty())) else backup(activity, store)
    }

    /** Fire-and-forget; Firestore queues it offline and sends it later. */
    fun backup(context: Context, store: GameStore) {
        if (!available(context) || user == null) return
        doc(context).set(SaveCodec.encode(store.all()) + ("updatedAt" to FieldValue.serverTimestamp()))
    }

    suspend fun signOut(context: Context) {
        Firebase.auth.signOut()
        CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest())
    }

    /** Play policy: users who can create an account must be able to delete it in the app. Deletes every game's save too. */
    suspend fun deleteAccount(context: Context) {
        val u = user ?: return
        val games = Firebase.firestore.collection("users").document(u.uid).collection("games").get().await()
        for (d in games.documents) d.reference.delete().await()
        u.delete().await() // may throw FirebaseAuthRecentLoginRequiredException; caller asks the user to sign in again
        signOut(context)
    }

    private fun doc(context: Context) =
        Firebase.firestore.collection("users").document(user!!.uid).collection("games").document(context.packageName)
}

/** SharedPreferences <-> Firestore. Firestore turns every Int into a Long, so values are grouped by type to restore them exactly. */
object SaveCodec {
    fun encode(all: Map<String, *>): Map<String, Any> = mapOf(
        "ints" to all.filterValues { it is Int },
        "longs" to all.filterValues { it is Long },
        "bools" to all.filterValues { it is Boolean },
        "strings" to all.filterValues { it is String },
    )

    fun decode(data: Map<String, Any?>): Map<String, Any> {
        fun group(name: String) = (data[name] as? Map<*, *>).orEmpty().entries
        val out = mutableMapOf<String, Any>()
        for ((k, v) in group("ints")) if (v is Number) out[k.toString()] = v.toInt()
        for ((k, v) in group("longs")) if (v is Number) out[k.toString()] = v.toLong()
        for ((k, v) in group("bools")) if (v is Boolean) out[k.toString()] = v
        for ((k, v) in group("strings")) if (v is String) out[k.toString()] = v
        return out
    }
}

private suspend fun <T> Task<T>.await(): T = suspendCancellableCoroutine { c ->
    addOnSuccessListener { c.resume(it) }
    addOnFailureListener { c.resumeWithException(it) }
}
